#!/usr/bin/env python3
"""Preserve pinned URP motion vectors around current/previous coastal grass bending."""
import argparse
from pathlib import Path
import uuid

ROOT = Path(__file__).resolve().parents[1]
SHADERS = ROOT / "Assets/Resources/Shaders"


def once(source, old, new):
    if source.count(old) != 1:
        raise ValueError("Coastal motion upstream hook changed: " + old[:100])
    return source.replace(old, new, 1)


def outputs():
    sources = list((ROOT / "Library/PackageCache").glob(
        "com.unity.render-pipelines.universal@*/ShaderLibrary/ObjectMotionVectors.hlsl"))
    if len(sources) != 1:
        raise ValueError("Expected one pinned URP ObjectMotionVectors source")
    motion = sources[0].read_text(encoding="utf8")
    motion = motion.replace("UNIVERSAL_OBJECT_MOTION_VECTORS_INCLUDED", "COASTAL_GRASS_MOTION_VECTORS_INCLUDED")
    motion = once(motion, '#include "Packages/com.unity.render-pipelines.universal/ShaderLibrary/UnityInput.hlsl"',
        '#include "Packages/com.unity.render-pipelines.universal/ShaderLibrary/UnityInput.hlsl"\n#include "CityCoastalGrassWind.hlsl"')
    motion = once(motion, '''#if _ALPHATEST_ON || APPLICATION_SPACE_WARP_MOTION_TRANSPARENT
    float2 uv                   : TEXCOORD0;
#endif''', '    float2 uv                   : TEXCOORD0; // rooted stem metadata also when alpha test is off')
    motion = once(motion, '    const VertexPositionInputs vertexInput = GetVertexPositionInputs(input.position.xyz);',
        '''    float4 currentPosition = input.position;
    CoastalGrassDisplace(currentPosition, input.uv);
    const VertexPositionInputs vertexInput = GetVertexPositionInputs(currentPosition.xyz);''')
    motion = motion.replace('mul(UNITY_MATRIX_M, input.position)', 'mul(UNITY_MATRIX_M, currentPosition)')
    motion = once(motion,
        '    output.previousPositionCSNoJitter = mul(_PrevViewProjMatrix, mul(UNITY_PREV_MATRIX_M, prevPos));',
        '    output.previousPositionCSNoJitter = mul(_PrevViewProjMatrix, float4(CoastalGrassPreviousPositionWS(prevPos, input.uv), 1));')
    header = "// Generated by tools/build-coastal-grass-motion-shader.py; pinned URP motion contract.\n"
    shader_path = SHADERS / "CityCoastalGrassLit.shader"
    shader = shader_path.read_text(encoding="utf8")
    old = '#include_with_pragmas "Packages/com.unity.render-pipelines.universal/ShaderLibrary/ObjectMotionVectors.hlsl"'
    new = '#include_with_pragmas "CityCoastalGrassMotionVectors.hlsl"'
    if old in shader:
        if shader.count(old) != 2:
            raise ValueError("Expected both regular and XR coastal motion passes")
        shader = shader.replace(old, new)
    elif shader.count(new) != 2:
        raise ValueError("Coastal motion include contract changed")
    tag = '            "AlwaysRenderMotionVectors" = "true"'
    if tag not in shader:
        shader = once(shader, '            "UniversalMaterialType" = "Lit"',
                      '            "UniversalMaterialType" = "Lit"\n' + tag)
    return {SHADERS / "CityCoastalGrassMotionVectors.hlsl": header + motion, shader_path: shader}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, value in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf8") != value:
                raise ValueError("Regenerate coastal motion shader: " + str(path))
        else:
            path.write_text(value, encoding="utf8", newline="\n")
            meta = Path(str(path) + ".meta")
            if not meta.exists():
                guid = uuid.uuid5(uuid.NAMESPACE_URL, path.relative_to(ROOT).as_posix()).hex
                meta.write_text(f"fileFormatVersion: 2\nguid: {guid}\nShaderIncludeImporter:\n  externalObjects: {{}}\n  userData:\n  assetBundleName:\n  assetBundleVariant:\n", encoding="utf8")
    print("Coastal motion retains rooted current/previous wind and the pinned regular/XR URP motion contract.")


if __name__ == "__main__":
    main()
