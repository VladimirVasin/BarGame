#!/usr/bin/env python3
"""Generate City instanced grass passes from the project's pinned rooted Lit shader."""
import argparse
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SHADERS=ROOT/"Assets/Resources/Shaders"

def outputs():
    shader=(SHADERS/"CityCoastalGrassLit.shader").read_text()
    shader=shader.replace('Bar Promenade/Coastal Grass Lit','Bar Promenade/City Grass Lit')
    shader=shader.replace('CityCoastalGrass','CityGrass').replace('CoastalGrass','CityGrass').replace('Coastal','CityGrass')
    shader=shader.replace('_Cull("__cull", Float) = 2.0','_Cull("__cull", Float) = 0.0')
    shader=shader.replace('CityGrassDisplace(input.positionOS, input.texcoord);',
                          'CityGrassDisplaceNormal(input.positionOS, input.normalOS, input.texcoord);')
    # DepthNormals calls its normal field `normal`, not `normalOS`.
    marker='Varyings CityGrassDepthNormalsVertex(Attributes input)'
    before,after=shader.split(marker)
    after=after.replace('input.normalOS, input.texcoord','input.normal, input.texcoord',1)
    shader=before+marker+after
    for upstream,local in [('LitForwardPass','CityGrassForwardPass'),('LitGBufferPass','CityGrassGBufferPass')]:
        shader=shader.replace(f'Packages/com.unity.render-pipelines.universal/Shaders/{upstream}.hlsl',f'{local}.hlsl')
    shader=shader.replace('CityGrassDisplace(input.positionOS, input.texcoord);',
                          'CityGrassDisplaceNormal(input.positionOS, input.normalOS, input.texcoord);')
    package=next((ROOT/'Library/PackageCache').glob('com.unity.render-pipelines.universal@*/Shaders'))
    result={SHADERS/'CityGrassLit.shader':shader}
    for source,target in [('LitForwardPass','CityGrassForwardPass'),('LitGBufferPass','CityGrassGBufferPass')]:
        text=(package/(source+'.hlsl')).read_text()
        text=text.replace('#include "LitInput.hlsl"','#include "Packages/com.unity.render-pipelines.universal/Shaders/LitInput.hlsl"')
        text=text.replace('struct Attributes\n{','struct Attributes\n{\n    half4 grassPigment : COLOR;')
        text=text.replace('struct Varyings\n{','struct Varyings\n{\n    half4 grassPigment : TEXCOORD11;')
        vertex='UNITY_INITIALIZE_VERTEX_OUTPUT_STEREO(output);'
        assert text.count(vertex)==1
        text=text.replace(vertex,vertex+'\n    output.grassPigment = input.grassPigment;')
        surface='InitializeStandardLitSurfaceData(input.uv, surfaceData);'
        assert text.count(surface)==1
        text=text.replace(surface,surface+'\n    surfaceData.albedo *= input.grassPigment.rgb;')
        result[SHADERS/(target+'.hlsl')]='// Generated by tools/build-city-grass-shader.py; pinned URP vertex pigment contract.\n'+text
    motion=(SHADERS/'CityCoastalGrassMotionVectors.hlsl').read_text()
    motion=motion.replace('tools/build-coastal-grass-motion-shader.py','tools/build-city-grass-shader.py')
    motion=motion.replace('COASTAL_GRASS','CITY_GRASS').replace('CityCoastalGrass','CityGrass').replace('CoastalGrass','CityGrass')
    result[SHADERS/'CityGrassMotionVectors.hlsl']=motion
    return {path:'\n'.join(line.rstrip() for line in text.splitlines())+'\n' for path,text in result.items()}

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for path,text in outputs().items():
        if args.check:
            assert path.read_text()==text, 'Regenerate '+str(path)
        else:path.write_text(text)
    print('City grass pinned forward/GBuffer/depth/shadow/motion pass validation passed')
if __name__=='__main__':main()
