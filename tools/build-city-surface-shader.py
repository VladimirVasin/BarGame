#!/usr/bin/env python3
"""Derive complete current URP Lit and wind passes around city material data."""
import argparse
import importlib.util
from pathlib import Path
import uuid

ROOT = Path(__file__).resolve().parents[1]
SHADERS = ROOT / "Assets/Resources/Shaders"


def outputs():
    path = ROOT / "tools/build-mothers-house-shader.py"
    spec = importlib.util.spec_from_file_location("house_surface_shader_source", path)
    source = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(source)
    result = {}
    header = "// Generated by tools/build-city-surface-shader.py; preserve complete URP passes and wind.\n"
    for old_path, value in source.outputs().items():
        name = old_path.name.replace("MothersHouseSurface.shader", "CitySurfaceLit.shader").replace("MothersHouse", "City")
        value = value[value.index('\n')+1:]
        value = value.replace("MothersHouseSurface", "CitySurface").replace(
            'Shader "Bar Promenade/Mothers House Surface"', 'Shader "Bar Promenade/City Surface"')
        result[SHADERS/name] = header+value
    foliage = (SHADERS/"LitFoliage.shader").read_text(encoding="utf8")
    foliage = foliage[foliage.index('Shader "'):]
    foliage = source.once(foliage,'Shader "Bar Promenade/Lit Foliage"',
                          'Shader "Bar Promenade/City Surface Foliage"')
    foliage = source.once(foliage,'    Properties\n    {','''    Properties
    {
        [NoScaleOffset] _SceneMaterialResponse("Physical slopes / roughness / cavity", 2D) = "gray" {}
        _SceneResponseStrength("Physical material response", Range(0,1)) = 0
        _SceneNormalStrength("Near material relief", Range(0,1)) = 0''')
    foliage = foliage.replace('#include "Packages/com.unity.render-pipelines.universal/Shaders/LitInput.hlsl"',
                              '#include "CitySurfaceInput.hlsl"')
    foliage = foliage.replace('#pragma target 2.0', '#pragma target 3.5', 1)
    foliage = source.once(foliage,
        '            #include "Packages/com.unity.render-pipelines.universal/Shaders/LitForwardPass.hlsl"',
        '''            #include "SurfaceMaterialResponse.hlsl"
            #define PROJECT_LIT_SURFACE_RESPONSE(uv, surfaceData) ApplySceneMaterialResponse(uv, surfaceData)
            #include "ProjectLitDirectionalLighting.hlsl"
            #include "Packages/com.unity.render-pipelines.universal/ShaderLibrary/Lighting.hlsl"
            #include "WarehouseAmbientVisibility.hlsl"
            #define UniversalFragmentPBR ProjectLitFragmentPBR
            #define InitializeStandardLitSurfaceData ProjectLitSurfaceData
            #include "CitySurfaceForwardPass.hlsl"
            #undef InitializeStandardLitSurfaceData
            #undef UniversalFragmentPBR
            #undef PROJECT_LIT_SURFACE_RESPONSE''')
    result[SHADERS/"CitySurfaceFoliage.shader"] = header+"\n".join(line.rstrip() for line in foliage.splitlines())+"\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, data in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf8") != data:
                raise ValueError("Regenerate city surface shader: "+str(path))
        else:
            path.write_text(data,encoding="utf8",newline="\n")
            meta=Path(str(path)+".meta")
            if not meta.exists():
                kind="ShaderImporter" if path.suffix==".shader" else "ShaderIncludeImporter"
                guid=uuid.uuid5(uuid.NAMESPACE_URL,path.relative_to(ROOT).as_posix()).hex
                meta.write_text(f"fileFormatVersion: 2\nguid: {guid}\n{kind}:\n  externalObjects: {{}}\n  userData:\n  assetBundleName:\n  assetBundleVariant:\n",encoding="utf8")
    print("City Lit/foliage surface hooks retain complete upstream passes, one material layout and wind.")


if __name__ == "__main__":
    main()
