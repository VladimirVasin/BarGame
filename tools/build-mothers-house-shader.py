#!/usr/bin/env python3
"""Retain complete project Lit/URP passes around the unique mother's-house response.

The Forward pass samples one aligned response and applies its physical slope
after input-normal initialization. Every pass shares one extended material
layout. --check detects project Lit/URP changes; no package source is edited.
"""
import argparse
from pathlib import Path
import uuid

ROOT = Path(__file__).resolve().parents[1]
SHADERS = ROOT / "Assets/Resources/Shaders"


def once(source, old, new):
    if source.count(old) != 1:
        raise ValueError("Mother's house shader upstream hook changed: " + old[:100])
    return source.replace(old, new, 1)


def outputs():
    packages = list((ROOT / "Library/PackageCache").glob(
        "com.unity.render-pipelines.universal@*/Shaders/LitInput.hlsl"))
    if len(packages) != 1:
        raise ValueError("Expected one imported URP LitInput source")
    source_folder = packages[0].parent
    shader = (SHADERS / "Lit.shader").read_text(encoding="utf-8")
    shader = shader[shader.index('Shader "'):]
    shader = once(shader, 'Shader "Bar Promenade/Lit"',
                  'Shader "Bar Promenade/Mothers House Surface"')
    shader = once(shader, '    Properties\n    {', '''    Properties
    {
        [NoScaleOffset] _SceneMaterialResponse("Unique slopes / roughness / cavity", 2D) = "gray" {}
        _SceneResponseStrength("Physical material response", Range(0,1)) = 0
        _SceneNormalStrength("Near material relief", Range(0,1)) = 0''')
    shader = shader.replace('#pragma target 2.0', '#pragma target 3.5', 1)
    shader = shader.replace(
        '#include "Packages/com.unity.render-pipelines.universal/Shaders/LitInput.hlsl"',
        '#include "MothersHouseSurfaceInput.hlsl"')
    shader = once(shader, '            #include "ProjectLitDirectionalLighting.hlsl"',
        '''            #include "SurfaceMaterialResponse.hlsl"
            #define PROJECT_LIT_SURFACE_RESPONSE(uv, surfaceData) ApplySceneMaterialResponse(uv, surfaceData)
            #include "ProjectLitDirectionalLighting.hlsl"''')
    shader = once(shader,
        '#include "Packages/com.unity.render-pipelines.universal/Shaders/LitForwardPass.hlsl"',
        '#include "MothersHouseSurfaceForwardPass.hlsl"')
    shader = once(shader, '            #undef InitializeStandardLitSurfaceData',
        '            #undef PROJECT_LIT_SURFACE_RESPONSE\n            #undef InitializeStandardLitSurfaceData')
    shader_input = packages[0].read_text(encoding="utf-8")
    shader_input = once(shader_input, 'UNITY_TEXTURE_STREAMING_DEBUG_VARS;\nCBUFFER_END',
        '''UNITY_TEXTURE_STREAMING_DEBUG_VARS;
half _SceneResponseStrength;
half _SceneNormalStrength;
CBUFFER_END''')
    forward = (source_folder / "LitForwardPass.hlsl").read_text(encoding="utf-8")
    forward = once(forward, '#include "LitInput.hlsl"', '#include "MothersHouseSurfaceInput.hlsl"')
    forward = once(forward, '    InitializeInputData(input, surfaceData.normalTS, inputData);',
        '''    InitializeInputData(input, surfaceData.normalTS, inputData);
    ApplySceneMaterialNormal(input.positionWS, input.uv, sceneMaterialHeightSlope, inputData.normalWS);''')
    header = '// Generated by tools/build-mothers-house-shader.py; edit its hooks or SurfaceMaterialResponse.hlsl.\n'
    return {SHADERS / name: header + '\n'.join(line.rstrip() for line in value.splitlines()) + '\n'
            for name, value in {
                'MothersHouseSurface.shader': shader,
                'MothersHouseSurfaceInput.hlsl': shader_input,
                'MothersHouseSurfaceForwardPass.hlsl': forward}.items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, value in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != value:
                raise ValueError("Regenerate mother's house shader: " + str(path))
        else:
            path.write_text(value, encoding='utf-8', newline='\n')
            meta = Path(str(path) + '.meta')
            if not meta.exists():
                importer = 'ShaderImporter' if path.suffix == '.shader' else 'ShaderIncludeImporter'
                guid = uuid.uuid5(uuid.NAMESPACE_URL, path.relative_to(ROOT).as_posix()).hex
                meta.write_text(f'fileFormatVersion: 2\nguid: {guid}\n{importer}:\n  externalObjects: {{}}\n  userData:\n  assetBundleName:\n  assetBundleVariant:\n', encoding='utf-8')
    print("Mother's house shader hooks retain complete project Lit/URP passes and material layout.")


if __name__ == '__main__':
    main()
